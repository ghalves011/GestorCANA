-- ---------------------------------------------------------------------
-- Tabela: jogadorpartida
-- ---------------------------------------------------------------------
CREATE TABLE public.jogadorpartida (
    jogador_id integer NOT NULL,
    partida_id integer NOT NULL,
    "time" character varying(255),
    status character varying(255),
    funcao character varying(255),
    gols integer DEFAULT 0,
    cartao_amarelo integer DEFAULT 0,
    cartao_vermelho integer DEFAULT 0,
    id integer NOT NULL,
    presente character varying(255)
);
 
ALTER TABLE public.jogadorpartida ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.jogadorpartida_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
 
 
-- ---------------------------------------------------------------------
-- Chaves primárias e únicas
-- ---------------------------------------------------------------------
ALTER TABLE ONLY public.temporada      ADD CONSTRAINT temporada_pkey      PRIMARY KEY (id);
ALTER TABLE ONLY public.temporada      ADD CONSTRAINT temporada_ano_key   UNIQUE (ano);
ALTER TABLE ONLY public.endereco       ADD CONSTRAINT endereco_pkey       PRIMARY KEY (id);
ALTER TABLE ONLY public.jogador        ADD CONSTRAINT jogador_pkey        PRIMARY KEY (id);
ALTER TABLE ONLY public.contribuicao   ADD CONSTRAINT contribuicao_pkey   PRIMARY KEY (id);
ALTER TABLE ONLY public.partida        ADD CONSTRAINT partida_pkey        PRIMARY KEY (id);
ALTER TABLE ONLY public.evento         ADD CONSTRAINT evento_pkey         PRIMARY KEY (id);
ALTER TABLE ONLY public.jogadorpartida ADD CONSTRAINT jogadorpartida_pkey PRIMARY KEY (jogador_id, partida_id);
 
 
-- ---------------------------------------------------------------------
-- Chaves estrangeiras
-- ---------------------------------------------------------------------
ALTER TABLE ONLY public.jogador
    ADD CONSTRAINT fk_jogador_endereco FOREIGN KEY (id_endereco) REFERENCES public.endereco(id) ON DELETE SET NULL;
ALTER TABLE ONLY public.jogador
    ADD CONSTRAINT fk_jogador_padrinho FOREIGN KEY (padrinho_id) REFERENCES public.jogador(id);
ALTER TABLE ONLY public.contribuicao
    ADD CONSTRAINT fk_contribuicao_jogador FOREIGN KEY (jogador_id) REFERENCES public.jogador(id);
ALTER TABLE ONLY public.partida
    ADD CONSTRAINT fk_partida_temporada FOREIGN KEY (temporada_id) REFERENCES public.temporada(id);
ALTER TABLE ONLY public.evento
    ADD CONSTRAINT fk_evento_jogador FOREIGN KEY (jogador_id) REFERENCES public.jogador(id);
ALTER TABLE ONLY public.evento
    ADD CONSTRAINT fk_evento_partida FOREIGN KEY (partida_id) REFERENCES public.partida(id);
ALTER TABLE ONLY public.jogadorpartida
    ADD CONSTRAINT fk_jogadorpartida_jogador FOREIGN KEY (jogador_id) REFERENCES public.jogador(id);
ALTER TABLE ONLY public.jogadorpartida
    ADD CONSTRAINT fk_jogadorpartida_partida FOREIGN KEY (partida_id) REFERENCES public.partida(id);
 
 
-- ---------------------------------------------------------------------
-- Row Level Security (padrão do Supabase; o app conecta como dono das
-- tabelas, então o RLS não bloqueia as consultas da API)
-- ---------------------------------------------------------------------
ALTER TABLE public.temporada      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.endereco       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jogador        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contribuicao   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.partida        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.evento         ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jogadorpartida ENABLE ROW LEVEL SECURITY;