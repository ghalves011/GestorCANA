-- ---------------------------------------------------------------------
-- Tabela: temporada
-- ---------------------------------------------------------------------
CREATE TABLE public.temporada (
    id integer NOT NULL,
    ano integer NOT NULL
);
 
CREATE SEQUENCE public.temporada_id_seq
    AS integer
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;
 
ALTER SEQUENCE public.temporada_id_seq OWNED BY public.temporada.id;
ALTER TABLE ONLY public.temporada ALTER COLUMN id SET DEFAULT nextval('public.temporada_id_seq'::regclass);
 
 
-- ---------------------------------------------------------------------
-- Tabela: endereco
-- ---------------------------------------------------------------------
CREATE TABLE public.endereco (
    id_endereco integer NOT NULL,
    logradouro character varying(255) NOT NULL,
    numero character varying(255),
    complemento character varying(255),
    bairro character varying(255),
    cidade character varying(255),
    estado character varying(255),
    cep character varying(255),
    id integer NOT NULL,
    rua character varying(255)
);
 
CREATE SEQUENCE public.endereco_id_endereco_seq
    AS integer
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;
 
ALTER SEQUENCE public.endereco_id_endereco_seq OWNED BY public.endereco.id_endereco;
ALTER TABLE ONLY public.endereco ALTER COLUMN id_endereco SET DEFAULT nextval('public.endereco_id_endereco_seq'::regclass);
 
ALTER TABLE public.endereco ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.endereco_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
 
 
-- ---------------------------------------------------------------------
-- Tabela: jogador
-- ---------------------------------------------------------------------
