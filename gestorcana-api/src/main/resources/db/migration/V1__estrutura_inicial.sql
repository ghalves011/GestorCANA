    posicao character varying(255),
    nivel integer,
    pedominante character varying(255),
    altura double precision,
    peso double precision,
    timeanterior character varying(255),
    tempoexperiencia integer,
    padrinho_id integer,
    graurelacaopadrinho character varying(255),
    estasuspenso boolean DEFAULT false,
    estaautorizado boolean DEFAULT true,
    mensalidadeemdia boolean DEFAULT true,
    numcamisa integer,
    golsiniciais integer DEFAULT 0,
    camarelosiniciais integer DEFAULT 0,
    cvermelhosiniciais integer DEFAULT 0,
    id_endereco integer,
    ativo boolean DEFAULT true
